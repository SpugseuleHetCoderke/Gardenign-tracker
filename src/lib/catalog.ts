/**
 * Turns a catalogue entry into the shape Prisma wants for a Species row plus
 * its care rules. Used by both the seed script and the "add from catalogue"
 * action, so the two can't drift apart.
 */
export function toSpeciesInput(entry: CatalogEntry) {
  const [sowInFrom, sowInTo] = entry.sowIndoors ?? [null, null];
  const [sowOutFrom, sowOutTo] = entry.sowOutdoors ?? [null, null];
  const [plantFrom, plantTo] = entry.plantOut ?? [null, null];
  const [harvestFrom, harvestTo] = entry.harvest ?? [null, null];

  return {
    fields: {
      name: entry.name,
      emoji: entry.emoji,
      category: entry.category,
      latinName: entry.latinName,
      lifecycle: entry.lifecycle,
      sunlight: entry.sunlight,
      soil: entry.soil,
      waterNeeds: entry.waterNeeds,
      spacing: entry.spacing,
      height: entry.height,
      sowIndoorsFromMonth: sowInFrom,
      sowIndoorsToMonth: sowInTo,
      sowOutdoorsFromMonth: sowOutFrom,
      sowOutdoorsToMonth: sowOutTo,
      plantOutFromMonth: plantFrom,
      plantOutToMonth: plantTo,
      harvestFromMonth: harvestFrom,
      harvestToMonth: harvestTo,
      generalNotes: entry.generalNotes,
      commonProblems: entry.commonProblems,
      companionPlants: entry.companionPlants,
    },
    careRules: (Object.entries(entry.care) as [ActivityType, [number, string]][]).map(
      ([activityType, [intervalDays, instructions]]) => ({
        activityType,
        intervalDays,
        instructions,
      }),
    ),
  };
}

/** Case- and accent-insensitive search over name, latin name and category. */
export function searchCatalog(query: string): CatalogEntry[] {
  const q = normalize(query);
  if (!q) return CATALOG;
  return CATALOG.filter((e) =>
    [e.name, e.latinName, e.slug].some((field) => normalize(field).includes(q)),
  );
}

function normalize(s: string): string {
  return s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "");
}
